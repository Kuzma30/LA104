#!/usr/bin/env python3
# Generates fontuni.h: Unicode lookup for the 8x14 font of the OS.
#  - code points of the CP437 font (0x80..0xFF and a few graphic control
#    codes) map to the glyphs already in font.h
#  - Cyrillic (U+0401..U+045F, U+0490/0491) and some punctuation come from
#    the 8x14 VGA console font CyrSlav-VGA14 of console-setup (Debian)
# usage: gen_fontuni.py CyrSlav-VGA14.psf.gz > fontuni.h
import sys, psf
glyphs, umap, w, h = psf.load(sys.argv[1])
assert (w, h) == (8, 14)
cp437 = {}
for b in range(0x80, 0x100):
    cp437[ord(bytes([b]).decode('cp437'))] = b
# graphic glyphs of control codes in the CP437 font
for cp, b in [(0x263a,1),(0x263b,2),(0x2665,3),(0x2666,4),(0x2663,5),(0x2660,6),(0x2022,7),
              (0x25ba,0x10),(0x25c4,0x11),(0x2195,0x12),(0x203c,0x13),(0x00b6,0x14),(0x00a7,0x15),
              (0x2191,0x18),(0x2193,0x19),(0x2192,0x1a),(0x2190,0x1b),(0x2194,0x1d),(0x25b2,0x1e),(0x25bc,0x1f),
              (0x25b6,0x10),(0x25c0,0x11)]:
    cp437.setdefault(cp, b)
extra = list(range(0x401, 0x460)) + [0x490, 0x491] + \
        [0x2018, 0x2019, 0x201a, 0x201c, 0x201d, 0x201e, 0x2013, 0x2014, 0x2026, 0x2116, 0xd7, 0x2030, 0x20ac]
extra = [c for c in extra if c in umap and c not in cp437]
o = sys.stdout
o.write('// generated by tools/font/gen_fontuni.py from CyrSlav-VGA14 (console-setup)\n')
o.write('// Unicode code points of the 8x14 font: CP437 glyphs of font.h and extra glyphs\n')
o.write('#pragma once\n#include <stdint.h>\n\n')
o.write('// code point -> byte of font.h, sorted\nstatic const uint16_t fontUniCp437[][2] = {\n')
for cp in sorted(cp437):
    o.write('  { 0x%04x, 0x%02x },\n' % (cp, cp437[cp]))
o.write('};\n\n// extra glyphs: code points (sorted) and 14 rows each\n')
o.write('static const uint16_t fontUniExtraCp[%d] = {\n' % len(extra))
for i in range(0, len(extra), 10):
    o.write('  ' + ', '.join('0x%04x' % c for c in extra[i:i+10]) + ',\n')
o.write('};\nstatic const uint8_t fontUniExtra[%d * 14] = {\n' % len(extra))
for c in extra:
    g = glyphs[umap[c]]
    o.write('  ' + ', '.join('0x%02x' % b for b in g) + ', // U+%04x %s\n' % (c, chr(c)))
o.write('};\n')
